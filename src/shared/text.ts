/**
 * 英語以外の言語で書かれている (と見なせる) か。画像生成のプロンプトを英語に翻訳するかの判定に使う。
 * 英語の文字 (ASCII) 以外の文字を含めば英語以外とする: 日本語・中国語・韓国語・キリル文字・アラビア文字・タイ文字や、
 * アクセント記号付きのラテン文字 (é, ü, ñ, ã など)。英語の文字だけで書かれた文 (アクセント記号の無いフランス語など) は
 * 英語と区別できないので対象外 (英語のプロンプトを翻訳に通すと、重み指定 (word:1.2) などが崩れるため)
 */
export const needsTranslation = (text: string) => /(?![\x00-\x7F])\p{L}/u.test(text)
